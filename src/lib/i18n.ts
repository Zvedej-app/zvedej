export const DICTS: Record<Lang, Dict> = { cs, en, sk };

export const LANG_LABELS: Record<Lang, string> = {
  cs: 'Čeština',
  en: 'English',
  sk: 'Slovenština',
};

export const LOCALES: Record<Lang, string> = { cs: 'cs-CZ', en: 'en-GB', sk: 'sk-SK' };

export function translate(lang: Lang, key: TKey, vars?: Record<string, string | number>) {
  let s = DICTS[lang][key] ?? DICTS.cs[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

type Forms = { one: string; few: string; many: string };
const PLURALS: Record<'workout' | 'set' | 'week', Record<Lang, Forms>> = {
  week: {
    cs: { one: 'týden', few: 'týdny', many: 'týdnů' },
    sk: { one: 'týždeň', few: 'týždne', many: 'týždňov' },
    en: { one: 'week', few: 'weeks', many: 'weeks' },
  },
  workout: {
    cs: { one: 'trénink', few: 'tréninky', many: 'tréninků' },
    sk: { one: 'tréning', few: 'tréningy', many: 'tréningov' },
    en: { one: 'workout', few: 'workouts', many: 'workouts' },
  },
  set: {
    cs: { one: 'nástup', few: 'nástupy', many: 'nástupů' },
    sk: { one: 'nástup', few: 'nástupy', many: 'nástupov' },
    en: { one: 'set', few: 'sets', many: 'sets' },
  },
};

/** Skloňování podle počtu (1 trénink, 2 tréninky, 5 tréninků). */
export function plural(lang: Lang, word: keyof typeof PLURALS, n: number) {
  const f = PLURALS[word][lang];
  const form = n === 1 ? f.one : n >= 2 && n <= 4 ? f.few : f.many;
  return `${n} ${form}`;
}
